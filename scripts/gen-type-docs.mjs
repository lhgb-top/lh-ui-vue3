// R25-TYPES 组件文档 TS 类型说明自动化（沿用 EVAL-1 的 TS compiler API 先例，无新依赖）
//
// 用法：
//   node scripts/gen-type-docs.mjs --check   全站漂移核对（有漂移时退出码 1）
//   node scripts/gen-type-docs.mjs --fix     重建全部组件文档页的「类型定义」章节（幂等）
//
// 事实来源（canonical）：
//   - packages/components/<name>/src/types.ts 中导出的 interface / type（含 JSDoc，原文提取）
//     —— 只收录用户可见类型：Lh 前缀且非 *Context / *Emits（provide/inject 管线不进文档）
//   - 该文件 `export type { ... } from '@lh-ui/share/core/*'` 再导出的核心类型（解析到
//     @lh-ui/share 已安装包的 es/core/<module> 声明文件提取原文，并在同文件内做引用闭包）
//   - `@lh-ui/share/core/shared`、`lh-types/*`、`@lh-ui/share/constants`、`vue` 为横切/外部类型，不提取
//
// 注入形态：页面以 `<!-- lh-types:begin -->` … `<!-- lh-types:end -->` 标记包裹的
// 「## 类型定义 / ## Type Definitions」章节，插入页尾页级 script 之前（无则追加文件尾）。
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const ts = require('typescript')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PKG_DIR = path.join(root, 'packages', 'components')
// core 源已收敛到 @lh-ui/share，随包以 .d.ts 形式发布：require.resolve 得到 lib/index.js，
// 往上两层即包根，es/core 下是与 src/core 同构的声明镜像（JSDoc 与常量字面量均保留）
const SHARE_ROOT = path.dirname(path.dirname(require.resolve('@lh-ui/share')))
const CORE_DIR = path.join(SHARE_ROOT, 'es', 'core')
const CONSTANTS_FILE = path.join(SHARE_ROOT, 'es', 'constants', 'index.d.ts')
const DOC_DIRS = { zh: path.join(root, 'docs', 'components'), en: path.join(root, 'docs', 'en', 'components') }
// 标记行本身不含中文（en 站点块内做到零中文）；定位用 BEGIN_PREFIX，
// 旧版中文标记块也能被前缀命中并在 --fix 时整体替换为新标记。
const BEGIN = '<!-- lh-types:begin (auto-generated by scripts/gen-type-docs.mjs, do not edit) -->'
const BEGIN_PREFIX = '<!-- lh-types:begin'
const END = '<!-- lh-types:end -->'

// ---------- 源码提取 ----------

function parseSource(file) {
  const text = fs.readFileSync(file, 'utf8')
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true)
  return { text, sf }
}

/** 带前置 JSDoc 的声明原文 */
function declText(parsed, node) {
  const ranges = ts.getLeadingCommentRanges(parsed.sf.getFullText(), node.getFullStart()) || []
  const start = ranges.length > 0 ? ranges[0].pos : node.getStart(parsed.sf)
  return parsed.text.slice(start, node.end).trimEnd()
}

function isInternalName(name) {
  return name.endsWith('Context') || name.endsWith('Emits') || !name.startsWith('Lh')
}

/** 收集一个 types 文件里的顶层 interface / type 声明（名字 → 节点） */
function collectDecls(sf) {
  const map = new Map()
  for (const stmt of sf.statements) {
    if (ts.isInterfaceDeclaration(stmt) || ts.isTypeAliasDeclaration(stmt)) {
      map.set(stmt.name.text, stmt)
    }
  }
  return map
}

/** 同文件引用闭包：已选声明的文本里出现同文件其他声明名则一并收录 */
function closeOverDecls(declMap, seeds) {
  const chosen = new Set()
  const queue = [...seeds]
  while (queue.length > 0) {
    const name = queue.pop()
    if (chosen.has(name) || !declMap.has(name)) continue
    chosen.add(name)
    const body = declMap.get(name).getText()
    for (const other of declMap.keys()) {
      if (!chosen.has(other) && new RegExp(`\\b${other}\\b`).test(body)) queue.push(other)
    }
  }
  return chosen
}

/** 解析 `export type { A, B as C } from '@lh-ui/share/core/x'`，返回 [{ module, imported, exported }] */
function collectReexports(sf) {
  const out = []
  for (const stmt of sf.statements) {
    if (!ts.isExportDeclaration(stmt) || !stmt.exportClause || !stmt.moduleSpecifier) continue
    const spec = stmt.moduleSpecifier.text
    const m = spec.match(/^@lh-ui\/share\/core\/([\w/-]+)$/)
    if (!m) continue
    for (const el of stmt.exportClause.elements) {
      out.push({ module: m[1], imported: el.propertyName ? el.propertyName.text : el.name.text, exported: el.name.text })
    }
  }
  return out
}

/** 解析 `import type { A, B as C } from '@lh-ui/share/core/x'`（Props 引用但未再导出的核心类型） */
function collectCoreImports(sf) {
  const out = []
  for (const stmt of sf.statements) {
    if (!ts.isImportDeclaration(stmt) || !stmt.importClause?.namedBindings || !stmt.moduleSpecifier) continue
    if (!(stmt.importClause.isTypeOnly ?? false)) continue
    const spec = stmt.moduleSpecifier.text
    const m = spec.match(/^@lh-ui\/share\/core\/([\w/-]+)$/)
    if (!m) continue
    for (const el of stmt.importClause.namedBindings.elements) {
      out.push({ module: m[1], imported: el.propertyName ? el.propertyName.text : el.name.text, exported: el.name.text })
    }
  }
  return out
}

/** core 声明文件候选：<dir>/types.d.ts、<dir>/index.d.ts、<dir>.d.ts */
function resolveDtsFile(dirOrFile) {
  const candidates = [
    path.join(dirOrFile, 'types.d.ts'),
    path.join(dirOrFile, 'index.d.ts'),
    `${dirOrFile}.d.ts`,
  ]
  return candidates.find((f) => fs.existsSync(f)) || null
}

/** 解析 core 模块内「本地声明 或 二级转发（re-export / import type）」的物理声明位置，深度受限 */
function resolveCoreDecl(module, name, depth = 0) {
  if (depth > 3) return null
  // module 形如 `table` 或子路径 `shared/popper`
  const file = resolveDtsFile(path.join(CORE_DIR, module))
  if (!file) return null
  const parsed = parseSource(file)
  const decls = collectDecls(parsed.sf)
  const fileBase = path.basename(file, '.d.ts')
  if (decls.has(name)) return { parsed, declMap: decls, name, module, fileBase }
  // 名字是转发：从 import type / export .. from 子句找来源
  const aliases = new Map() // 本名 -> { spec, original }
  for (const stmt of parsed.sf.statements) {
    let spec = null
    let elements = null
    if (ts.isImportDeclaration(stmt) && stmt.importClause?.namedBindings && stmt.moduleSpecifier) {
      spec = stmt.moduleSpecifier.text
      elements = stmt.importClause.namedBindings.elements
    } else if (ts.isExportDeclaration(stmt) && stmt.exportClause && stmt.moduleSpecifier) {
      spec = stmt.moduleSpecifier.text
      elements = stmt.exportClause.elements
    }
    if (!spec || !elements) continue
    for (const el of elements) {
      const local = el.propertyName ? el.propertyName.text : el.name.text
      aliases.set(local, { spec, original: el.propertyName ? el.propertyName.text : el.name.text })
    }
  }
  const hit = aliases.get(name)
  if (!hit) return null
  const m = hit.spec.match(/^@lh-ui\/share\/core\/([\w/-]+)$/)
  if (m) return resolveCoreDecl(m[1], hit.original, depth + 1)
  // 声明文件内部用相对路径转发（./logic、../shared/popper），按 d.ts 候选解析
  if (hit.spec.startsWith('.')) {
    const relFile = resolveDtsFile(path.resolve(path.dirname(file), hit.spec))
    if (!relFile) return null
    const relParsed = parseSource(relFile)
    const relDecls = collectDecls(relParsed.sf)
    if (!relDecls.has(hit.original)) return null
    return { parsed: relParsed, declMap: relDecls, name: hit.original, module, fileBase: path.basename(relFile, '.d.ts') }
  }
  return null
}

/** 解析无 from 的本地别名再导出 `export type { A as B }`（A 为本文件或已 import 的名字） */
function collectBareAliases(sf) {
  const map = new Map()
  for (const stmt of sf.statements) {
    if (!ts.isExportDeclaration(stmt) || !stmt.exportClause || stmt.moduleSpecifier) continue
    for (const el of stmt.exportClause.elements) {
      const local = el.propertyName ? el.propertyName.text : el.name.text
      map.set(local, el.name.text)
    }
  }
  return map
}

/** 判断 const 声明是否内部管线（InjectionKey / Symbol）——不进文档 */
function isInternalConst(parsed, node) {
  const text = node.getText(parsed.sf)
  return /InjectionKey|Symbol\(/.test(text)
}

/** 提取一份源文件里用户可见的 `export const LH_*` 声明（带 JSDoc 原文） */
function collectConstDecls(parsed, origin) {
  const out = []
  for (const stmt of parsed.sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    const isExported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    if (!isExported) continue
    const name = stmt.declarationList.declarations[0]?.name.getText(parsed.sf)
    if (!name || !name.startsWith('LH_') || isInternalConst(parsed, stmt)) continue
    out.push({ name, origin, source: declText(parsed, stmt) })
  }
  return out
}

/** 组件相关常量清单：core/<name> 模块 + @lh-ui/share/constants 中被该组件 types.ts 引用的常量 */
function extractComponentConsts(component) {
  const out = []
  const seen = new Set()
  const push = (items) => {
    for (const c of items) {
      if (seen.has(c.name)) continue
      seen.add(c.name)
      out.push(c)
    }
  }
  // 1) core/<name> 的 types.d.ts 与 logic.d.ts（@lh-ui/share 发布声明）
  for (const base of ['types.d.ts', 'logic.d.ts']) {
    const file = path.join(CORE_DIR, component, base)
    if (fs.existsSync(file)) push(collectConstDecls(parseSource(file), `@lh-ui/share/core/${component}`))
  }
  // 2) @lh-ui/share/constants：组件 types.ts 引用了哪些常量
  const typesFile = path.join(PKG_DIR, component, 'src', 'types.ts')
  if (fs.existsSync(typesFile)) {
    const parsed = parseSource(typesFile)
    const wanted = new Set()
    for (const stmt of parsed.sf.statements) {
      if (!ts.isImportDeclaration(stmt) || !stmt.importClause?.namedBindings || !stmt.moduleSpecifier) continue
      if (stmt.moduleSpecifier.text !== '@lh-ui/share/constants') continue
      for (const el of stmt.importClause.namedBindings.elements) wanted.add(el.name.text)
    }
    if (wanted.size > 0 && fs.existsSync(CONSTANTS_FILE)) {
      const constParsed = parseSource(CONSTANTS_FILE)
      const decls = new Map()
      for (const stmt of constParsed.sf.statements) {
        if (!ts.isVariableStatement(stmt)) continue
        const isExported = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
        if (!isExported) continue
        const name = stmt.declarationList.declarations[0]?.name.getText(constParsed.sf)
        if (name) decls.set(name, stmt)
      }
      // 引用闭包（如 LH_SIZE_DEFAULT 引用 LH_SIZE_CONST）
      const queue = [...wanted].filter((n) => decls.has(n))
      while (queue.length > 0) {
        const name = queue.pop()
        if (seen.has(name)) continue
        seen.add(name)
        push([{ name, origin: '@lh-ui/share/constants', source: declText(constParsed, decls.get(name)) }])
        const body = decls.get(name).getText(constParsed.sf)
        for (const other of decls.keys()) {
          if (!seen.has(other) && new RegExp(`\\b${other}\\b`).test(body)) queue.push(other)
        }
      }
    }
  }
  return out
}

/** 组件的完整类型清单：[{ name, origin, source }]，origin 用于 summary 标注来源模块 */
function extractComponentTypes(component) {
  const typesFile = path.join(PKG_DIR, component, 'src', 'types.ts')
  if (!fs.existsSync(typesFile)) return []
  const parsed = parseSource(typesFile)
  const decls = collectDecls(parsed.sf)
  const results = []
  const seen = new Set()

  // 1) 本地声明（用户可见的）
  const localSeeds = [...decls.keys()].filter((n) => !isInternalName(n))
  for (const name of localSeeds) {
    results.push({ name, origin: null, source: declText(parsed, decls.get(name)) })
    seen.add(name)
  }

  // 2) 再导出 + import type 引用的核心类型：递归解析物理位置 + 物理文件内引用闭包
  const bareAliases = collectBareAliases(parsed.sf)
  const refs = [...collectReexports(parsed.sf), ...collectCoreImports(parsed.sf)]
  const byFile = new Map() // 物理文件 -> { parsed, declMap, seeds: Map<localName, publicName>, module, fileBase }
  for (const r of refs) {
    const hit = resolveCoreDecl(r.module, r.imported)
    if (!hit) continue
    const key = hit.parsed.text
    if (!byFile.has(key)) {
      byFile.set(key, { parsed: hit.parsed, declMap: hit.declMap, seeds: new Map(), module: hit.module, fileBase: hit.fileBase })
    }
    byFile.get(key).seeds.set(hit.name, r.exported)
  }
  for (const { parsed: p, declMap, seeds, module, fileBase } of byFile.values()) {
    const closed = closeOverDecls(declMap, [...seeds.keys()])
    for (const localName of closed) {
      // 公开名优先取本文件尾部的别名再导出（如 LhPlacement → LhPopconfirmPlacement）
      const publicName = bareAliases.get(localName) ?? seeds.get(localName) ?? localName
      if (seen.has(publicName)) continue
      seen.add(publicName)
      const origin = fileBase === 'types' || module.endsWith(fileBase) ? `@lh-ui/share/core/${module}` : `@lh-ui/share/core/${module} (${fileBase}.d.ts)`
      results.push({ name: publicName, origin, source: declText(p, declMap.get(localName)) })
    }
  }
  return results
}

// ---------- 文档注入 ----------

const HEADING = { zh: '## 类型定义', en: '## Type Definitions' }

/**
 * en 页剥离全部注释行：源码注释按仓库约定保持中文（JSDoc 与 `//` 行注释都算），
 * en 类型章节只保留签名（类型名与结构自明，避免 en 页残留中文或需要翻译维护源码注释）。
 * `--check` 与 `--fix` 共用此转换，天然无漂移。
 */
function stripSourceComments(text) {
  return text
    .replace(/^[ \t]*\/\*[\s\S]*?\*\/[ \t]*$\n?/gm, '')
    .split('\n')
    .filter((line) => !/^[ \t]*\/\//.test(line))
    .join('\n')
}

function buildSection(lang, component, types, consts) {
  if (types.length === 0 && consts.length === 0) return null
  const detailText = lang === 'zh' ? '点击各条目展开查看完整定义' : 'click each entry to expand'
  const propsRef = lang === 'zh' ? '属性说明见上方 Props 表' : 'see the Props table above for attribute descriptions'
  const introTypes =
    lang === 'zh'
      ? `本组件对外导出的 TypeScript 类型结构如下（自动提取自 \`packages/components/${component}/src/types.ts\` 与 \`@lh-ui/share/core/*\` 源码，${detailText}；${propsRef}）：`
      : `The TypeScript type structures exported by this component (auto-extracted from \`packages/components/${component}/src/types.ts\` and \`@lh-ui/share/core/*\` sources; ${detailText}; ${propsRef}):`
  const introConsts =
    lang === 'zh'
      ? '本组件用到的公开常量如下（可在 Props 表的「类型 / 默认值」列点击同名条目跳转至此）：'
      : 'Public constants used by this component (linked from the Type / Default columns in the Props table above):'
  const originTag = (origin) => (origin ? ` <sub>${lang === 'zh' ? `（来自 ${origin}）` : `(from ${origin})`}</sub>` : '')
  const srcOf = (source) => (lang === 'en' ? stripSourceComments(source) : source)
  const lines = [BEGIN, '', HEADING[lang], '']
  if (types.length > 0) {
    lines.push(introTypes, '')
    for (const t of types) {
      lines.push(`<details id="type-${t.name}">`)
      lines.push(`<summary><code>${t.name}</code>${originTag(t.origin)}</summary>`)
      lines.push('')
      lines.push('```ts')
      lines.push(srcOf(t.source))
      lines.push('```')
      lines.push('')
      lines.push('</details>')
      lines.push('')
    }
  }
  if (consts.length > 0) {
    lines.push(`### ${lang === 'zh' ? '常量' : 'Constants'}`, '', introConsts, '')
    for (const c of consts) {
      lines.push(`<details id="const-${c.name}">`)
      lines.push(`<summary><code>${c.name}</code>${originTag(c.origin)}</summary>`)
      lines.push('')
      lines.push('```ts')
      lines.push(srcOf(c.source))
      lines.push('```')
      lines.push('')
      lines.push('</details>')
      lines.push('')
    }
  }
  lines.push(END)
  return lines.join('\n')
}

/** 找页尾「页级 script」（围栏外最后一个 <script setup>）的行首插入点，无则返回文末 */
function findInsertPos(src) {
  const stripped = src.replace(/^```[\s\S]*?^```$/gm, (m) => ' '.repeat(m.length))
  const idx = stripped.lastIndexOf('<script setup')
  if (idx === -1) return src.length
  const lineStart = src.lastIndexOf('\n', idx)
  return lineStart === -1 ? 0 : lineStart + 1
}

function processPage(file, lang, component, types, consts) {
  const src = fs.readFileSync(file, 'utf8')
  // 与文件现有换行符一致（api:fix 会全文件归一 EOL，章节须跟随）
  const eol = src.includes('\r\n') ? '\r\n' : '\n'
  const section = buildSection(lang, component, types, consts).replace(/\n/g, eol)
  const beginIdx = src.indexOf(BEGIN_PREFIX)
  if (beginIdx !== -1) {
    const endIdx = src.indexOf(END, beginIdx)
    if (endIdx === -1) throw new Error(`${file}: ${BEGIN} 无对应 ${END}`)
    if (section === null) return false // 不主动删既有章节（源码类型清空属异常，人工处理）
    const next = src.slice(0, beginIdx) + section + src.slice(endIdx + END.length)
    if (next === src) return false
    fs.writeFileSync(file, next)
    return true
  }
  if (section === null) return false
  const pos = findInsertPos(src)
  const head = src.slice(0, pos).replace(/\n*$/, '\n')
  const tail = src.slice(pos)
  fs.writeFileSync(file, head + `\n${section}\n` + (pos >= src.length ? '' : tail.replace(/^\n+/, '\n')))
  return true
}

// ---------- 主流程（被 import 时跳过，供 gen-api-tables 复用提取函数） ----------

const isDirectRun = process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)

/** 供 gen-api-tables 使用：某组件在文档页可跳转的锚点名（类型 + 常量） */
export function getDocAnchors(component) {
  const names = new Set()
  for (const t of extractComponentTypes(component)) names.add(t.name)
  for (const c of extractComponentConsts(component)) names.add(c.name)
  return names
}

const isCheck = isDirectRun && process.argv.includes('--check')
const isFix = isDirectRun && process.argv.includes('--fix')

if (isDirectRun) {
  const components = fs
    .readdirSync(PKG_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()

  let drift = 0
  let changedCount = 0
  const typeCounts = []

  for (const component of components) {
    const types = extractComponentTypes(component)
    const consts = extractComponentConsts(component)
    if (types.length > 0 || consts.length > 0) typeCounts.push(`${component}=${types.length}+${consts.length}`)
    for (const [lang, dir] of Object.entries(DOC_DIRS)) {
      const file = path.join(dir, `${component}.md`)
      if (!fs.existsSync(file)) {
        console.error(`[缺文档] ${file}`)
        drift++
        continue
      }
      if (isFix) {
        if (processPage(file, lang, component, types, consts)) changedCount++
      } else {
        const src = fs.readFileSync(file, 'utf8')
        const expected = buildSection(lang, component, types, consts)
        const beginIdx = src.indexOf(BEGIN_PREFIX)
        if (expected === null) {
          if (beginIdx !== -1) {
            console.error(`[漂移] ${path.relative(root, file)}：源码无类型但文档残留章节`)
            drift++
          }
          continue
        }
        if (beginIdx === -1) {
          console.error(`[漂移] ${path.relative(root, file)}：缺少类型定义章节`)
          drift++
          continue
        }
        const endIdx = src.indexOf(END, beginIdx)
        const actual = src.slice(beginIdx, endIdx + END.length).replace(/\r\n/g, '\n')
        if (actual !== expected) {
          console.error(`[漂移] ${path.relative(root, file)}：章节内容与源码不一致`)
          drift++
        }
      }
    }
  }

  if (isFix) {
    console.log(`--fix：更新 ${changedCount} 个页面；各组件类型+常量条目数：${typeCounts.join(' ')}`)
  } else {
    console.log(`核对 ${components.length} 个组件 × 2 语言，漂移 ${drift} 处。`)
  }
  if (isCheck && drift > 0) process.exitCode = 1
}
